// Regenerate from https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt.
// Usage: node scripts/generate-case-folding.mjs /path/to/CaseFolding.txt
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const source = readFileSync(process.argv[2], 'utf8');
if (createHash('sha256').update(source).digest('hex') !== 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183') {
  throw new Error('Expected the pinned Unicode 17.0.0 CaseFolding.txt');
}
const rows = [];
for (const line of source.split('\n')) {
  const [code, status, mapping] = line.split(';').map((part) => part.trim());
  if (status !== 'C' && status !== 'F') continue;
  const escaped = mapping.split(' ').map((value) => `\\u{${value}}`).join('');
  rows.push(`  0x${code}: '${escaped}',`);
}
writeFileSync(new URL('../packages/livesync-contracts/src/unicode-case-fold.ts', import.meta.url),
  `// Generated by scripts/generate-case-folding.mjs; do not edit by hand.
// Unicode 17.0.0 full default folding (C + F, excluding Turkic mappings).
// Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
// License: ../UNICODE-LICENSE.txt
const mappings: Readonly<Record<number, string>> = {
${rows.join('\n')}
};

export function unicodeCaseFold(value: string): string {
  return Array.from(value, (character) => mappings[character.codePointAt(0)!] ?? character).join('');
}
`);
